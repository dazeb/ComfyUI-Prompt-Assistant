def extract_chinese_strings(filepath):
    """Extract unique Chinese strings from a file."""
    with open(filepath, 'r', encoding='utf-8') as f:
        content = f.read()
    
    # Find all Chinese strings (in quotes or standalone)
    # Match strings like "中文" or '中文' or just 中文 in comments
    patterns = [
        r'"([^"]*[\u4e00-\u9fff][^"]*)"',  # "中文..."
        r"'([^']*[\u4e00-\u9fff][^']*)'",  # '中文...'
        r'`([^`]*[\u4e00-\u9fff][^`]*)`',  # `中文...`
        r'//.*?([\u4e00-\u9fff].*?)(?:\n|$)',  # // 中文...
        r'/\*.*?([\u4e00-\u9fff].*?)\*/',  # /* 中文... */
    ]
    
    all_matches = set()
    for pattern in patterns:
        matches = re.findall(pattern, content)
        for m in matches:
            # Extract Chinese portions
            cn_parts = CN_RE.findall(m)
            for part in cn_parts:
                if len(part) >= 1:
                    all_matches.add(part)
    
    return sorted(all_matches, key=len, reverse=True)

