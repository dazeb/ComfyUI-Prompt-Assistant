    if len(sys.argv) < 2:
        print("Usage: python3 translate_js.py <file_path>")
        sys.exit(1)
    
    filepath = sys.argv[1]
    strings = extract_chinese_strings(filepath)
    print(f"Found {len(strings)} unique Chinese strings in {filepath}")
    for s in strings:
        translated = translate_simple(s)
        print(f"  '{s}' -> '{translated}'")
